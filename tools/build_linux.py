import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from refrata import __version__  # noqa: E402
from refrata.assoc import mime_types  # noqa: E402

OUT = ROOT / "dist" / "linux"
WORK = Path(os.environ.get("REFRATA_LINUX_WORK", Path.home() / "refrata-build"))   # a Linux file system

