"""Linux build: PyInstaller app folder, a .deb (Ubuntu, Debian, Mint…) and a .tar.gz.

    python3 tools/build_linux.py            # run on Linux (or WSL); results in dist/linux/

libVLC is not bundled: the .deb depends on the distribution's libvlc5 and VLC plugins, which the
distribution keeps patched. The app goes to /opt/refrata, with `refrata` on the PATH, a menu entry
and the icon. Updates on Linux come from a new .deb (the app's updater opens the download page).
"""
